"""Export nilai dari tabel "Total" (sheet 9.1 fix ... 9.9 fix) menjadi data.js.

Skor = jumlah nilai numerik pada kolom Total 1..3 (3 tugas).
Skor tertinggi tetap 300 = 100 x 3 tugas.
Nilai non-numerik (mis. "s", "a", "+", spasi) dianggap belum ada nilai -> null.
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

import openpyxl

SOURCE = Path(
    r"C:\Users\Administrator\Downloads\Data Nilai Kelas 9.xlsx"
)
SHEETS = [f"9.{i} fix" for i in range(1, 10)]
TOTAL_START_COL = 17  # Q = "Total / 1"
TOTAL_END_COL = 19  # S = "Total / 3"
MAX_SCORE = 300  # 100 x 3 tugas


def to_number(value):
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return int(value) if float(value).is_integer() else round(float(value), 2)
    return None


def as_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value).strip()


def export(source: Path, output: Path) -> None:
    workbook = openpyxl.load_workbook(source, data_only=True)
    students = []
    used_sheets = []

    for sheet_name in SHEETS:
        if sheet_name not in workbook.sheetnames:
            continue
        used_sheets.append(sheet_name)
        sheet = workbook[sheet_name]
        kelas = sheet_name.split()[0]

        for row in range(3, sheet.max_row + 1):
            nama = as_text(sheet.cell(row, 5).value)
            if not nama:
                continue

            total_values = [
                to_number(sheet.cell(row, col).value)
                for col in range(TOTAL_START_COL, TOTAL_END_COL + 1)
            ]
            score = sum(value for value in total_values if value is not None)

            students.append(
                {
                    "no": to_number(sheet.cell(row, 1).value),
                    "kelas": kelas,
                    "nama": nama,
                    "jk": as_text(sheet.cell(row, 6).value),
                    "nisn": as_text(sheet.cell(row, 2).value),
                    "nis": as_text(sheet.cell(row, 3).value),
                    "tugas": total_values,
                    "score": score,
                }
            )

    if not students:
        raise RuntimeError("Tidak ada siswa yang ditemukan pada tabel Total.")

    max_score = MAX_SCORE
    payload = {
        "meta": {
            "source": source.name,
            "sheets": used_sheets,
            "rule": "Skor = jumlah nilai pada tabel Total (Total 1 s.d. Total 3); skor maksimal 300",
            "maxScore": max_score,
            "studentCount": len(students),
            "generatedAt": date.today().isoformat(),
        },
        "students": students,
    }

    content = (
        "// Generated by tools/export_data.py -- jangan edit manual.\n"
        "const RANKING_DATA = "
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + ";\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"Exported {len(students)} students -> {output}")
    print(f"Max score: {max_score}")


if __name__ == "__main__":
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SOURCE
    dest = (
        Path(sys.argv[2])
        if len(sys.argv) > 2
        else Path(__file__).resolve().parents[1] / "data.js"
    )
    export(src, dest)
